using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.Json;

namespace DesktopAutomationTest.Core.Agent;

/// <summary>
/// Converts recorded <see cref="SessionRecord"/> files into pure C# xUnit test methods
/// or Reqnroll/Gherkin BDD feature scenarios.
/// Enables AI Agents to record live UI interactions once and generate production-grade test code.
/// </summary>
public static class SessionTestGenerator
{
    /// <summary>
    /// Generates a standalone C# xUnit test method string using IDriver and FluentAssertions.
    /// </summary>
    /// <param name="session">The recorded session data.</param>
    /// <param name="testMethodName">Optional name for the generated test method.</param>
    public static string GenerateCSharpTest(SessionRecord session, string? testMethodName = null)
    {
        testMethodName ??= !string.IsNullOrWhiteSpace(session.Label)
            ? SanitizeIdentifier(session.Label)
            : $"Test_RecordedSession_{session.SessionId}";

        var sb = new StringBuilder();
        sb.AppendLine("    [Fact]");
        sb.AppendLine($"    public void {testMethodName}()");
        sb.AppendLine("    {");
        sb.AppendLine("        // Generated by AutoNex SessionTestGenerator");
        if (!string.IsNullOrEmpty(session.AppPath))
        {
            sb.AppendLine($"        // Target App: {session.AppPath}");
        }
        sb.AppendLine();
        sb.AppendLine("        using var driver = DriverFactory.CreateFlauiDriver();");
        sb.AppendLine($"        driver.Initialize(@\"{session.AppPath ?? "path/to/app.exe"}\");");
        sb.AppendLine();

        foreach (var step in session.Steps)
        {
            var code = ConvertStepToCSharp(step);
            if (!string.IsNullOrEmpty(code))
            {
                sb.AppendLine($"        {code}");
            }
        }

        sb.AppendLine("    }");
        return sb.ToString();
    }

    /// <summary>
    /// Generates a complete C# test fixture file containing the session test.
    /// </summary>
    public static string GenerateCSharpFixture(SessionRecord session, string className = "RecordedFlowTests", string namespaceName = "DesktopAutomationTest.Tests")
    {
        var methodCode = GenerateCSharpTest(session);
        return $$"""
using System;
using Xunit;
using FluentAssertions;
using DesktopAutomationTest.Core;

namespace {{namespaceName}};

public class {{className}}
{
{{methodCode}}
}
""";
    }

    /// <summary>
    /// Generates a Gherkin / Reqnroll BDD feature scenario from the recorded session.
    /// </summary>
    public static string GenerateGherkinScenario(SessionRecord session, string? scenarioTitle = null)
    {
        scenarioTitle ??= session.Label ?? $"Recorded Flow {session.SessionId}";

        var sb = new StringBuilder();
        sb.AppendLine($"  Scenario: {scenarioTitle}");
        sb.AppendLine($"    Given the application \"{session.AppPath ?? "App.exe"}\" is launched");

        foreach (var step in session.Steps)
        {
            var line = ConvertStepToGherkin(step);
            if (!string.IsNullOrEmpty(line))
            {
                sb.AppendLine($"    {line}");
            }
        }

        return sb.ToString();
    }

    // ── Internal Helpers ───────────────────────────────────────────────────────

    private static string ConvertStepToCSharp(SessionStep step)
    {
        var id = step.AutomationId;
        var val = step.Value ?? "";

        return step.Action.ToLowerInvariant() switch
        {
            "click" => $"driver.ClickByAutomationId(\"{id}\").Should().BeTrue(\"clicking {id} should succeed\");",
            "double_click" => $"driver.DoubleClickByAutomationId(\"{id}\").Should().BeTrue();",
            "right_click" => $"driver.RightClickByAutomationId(\"{id}\").Should().BeTrue();",
            "hover" => $"driver.HoverOverByAutomationId(\"{id}\").Should().BeTrue();",
            "type" => $"driver.TypeTextByAutomationId(\"{id}\", \"{Escape(val)}\").Should().BeTrue();",
            "check" => $"driver.SetCheckboxByAutomationId(\"{id}\", true).Should().BeTrue();",
            "uncheck" => $"driver.SetCheckboxByAutomationId(\"{id}\", false).Should().BeTrue();",
            "select" => $"driver.SelectComboBoxItemByText(\"{id}\", \"{Escape(val)}\").Should().BeTrue();",
            "radio" => $"driver.SelectRadioButtonByAutomationId(\"{id}\").Should().BeTrue();",
            "press_key" => $"driver.PressKey(\"{Escape(val)}\").Should().BeTrue();",
            "send_keys" => $"driver.SendKeys(\"{Escape(val)}\").Should().BeTrue();",
            "assert_text" => $$"""
driver.TryGetTextByAutomationId("{{id}}", out var text{{step.Index}}).Should().BeTrue();
        text{{step.Index}}.Should().Contain("{{Escape(val)}}");
""",
            _ => $"// Unsupported action: {step.Action}"
        };
    }

    private static string ConvertStepToGherkin(SessionStep step)
    {
        var id = step.AutomationId;
        var val = step.Value ?? "";

        return step.Action.ToLowerInvariant() switch
        {
            "click" => $"When I click \"{id}\"",
            "type" => $"When I type \"{val}\" into \"{id}\"",
            "check" => $"When I check \"{id}\"",
            "uncheck" => $"When I uncheck \"{id}\"",
            "select" => $"When I select \"{val}\" from \"{id}\"",
            "radio" => $"When I select radio option \"{id}\"",
            "assert_text" => $"Then \"{id}\" should contain text \"{val}\"",
            _ => $"And I perform \"{step.Action}\" on \"{id}\""
        };
    }

    private static string SanitizeIdentifier(string name)
    {
        var sb = new StringBuilder();
        foreach (var c in name)
        {
            if (char.IsLetterOrDigit(c))
                sb.Append(c);
            else if (sb.Length > 0 && sb[^1] != '_')
                sb.Append('_');
        }

        var res = sb.ToString().Trim('_');
        return string.IsNullOrEmpty(res) || char.IsDigit(res[0]) ? $"Flow_{res}" : res;
    }

    private static string Escape(string s) => s.Replace("\"", "\\\"");
}

